import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { FAQ_ITEMS, faqJsonLd } from '../../src/components/home/FAQ';
import { PRODUCT_DISPLAY } from '../../src/lib/products/catalog';

const read = (p: string) => readFileSync(p, 'utf8');

test('the FAQ answers the questions people ask first, with no invented promises', () => {
  const all = FAQ_ITEMS.map((i) => `${i.q} ${i.a}`).join(' ').toLowerCase();
  for (const topic of ['prediction', 'accurate', 'birth time', 'free', 'private', 'at least 13']) assert.ok(all.includes(topic), topic);
  assert.doesNotMatch(all, /refund|money-back|guarantee|app store|testflight|\$\d/);
  assert.ok(FAQ_ITEMS.length >= 6);
});

test('search engines read the same questions and answers people see', () => {
  const ld = faqJsonLd();
  assert.equal(ld['@type'], 'FAQPage');
  assert.equal(ld.mainEntity.length, FAQ_ITEMS.length);
  assert.equal(ld.mainEntity[0].acceptedAnswer.text, FAQ_ITEMS[0].a);
});

test('the FAQ uses real disclosure elements and keeps keyboard focus visible', () => {
  const src = read('src/components/home/FAQ.tsx');
  const css = read('src/app/globals.css');
  assert.match(src, /<details/);
  assert.match(src, /<summary/);
  assert.match(css, /\.faq-summary:focus-visible/);
  assert.match(css, /min-height: 56px/);
});

test('both new sections are on the homepage and in the navigation', () => {
  assert.match(read('src/app/page.tsx'), /<WhatsInside \/>[\s\S]*<FAQ \/>/);
  assert.match(read('src/components/navigation/Nav.tsx'), /href: '\/#faq',\s+label: 'FAQ'/);
  assert.match(read('src/components/navigation/Footer.tsx'), /'\/#faq'/);
});

test('product cards use plain words, not bracket tags or shouted labels', () => {
  for (const p of Object.values(PRODUCT_DISPLAY)) {
    assert.doesNotMatch(p.eyebrow, /[\[\]]/);
    for (const i of p.includes) assert.notEqual(i.label, i.label.toUpperCase());
  }
});

test('the report section shows real pages, labelled as fact, and works without pinning', () => {
  const src = read('src/components/home/WhatsInside.tsx');
  // Six real pages: a section opener and a chart page for each of the three lenses.
  for (const f of ['vehicle-spread', 'vehicle-chart', 'road-spread', 'road-chart', 'stoplight-spread', 'stoplight-chart']) {
    assert.ok(src.includes(`/report/${f}.webp`), f);
    assert.ok(existsSync(`public/report/${f}.webp`), `public/report/${f}.webp exists`);
  }
  // Every page carries alt text and a label.
  assert.equal((src.match(/alt: '/g) ?? []).length, 6);
  assert.equal((src.match(/spec: '/g) ?? []).length, 6);
  // Pinning is an enhancement: the rail falls back to a keyboard-reachable swipe strip.
  assert.match(src, /const \[pinned, setPinned\] = useState\(false\)/);
  assert.match(src, /prefers-reduced-motion: reduce/);
  assert.match(src, /tabIndex=\{pinned \? undefined : 0\}/);
  // A touch screen swipes the rail directly. Driving it from vertical scroll stutters,
  // because touch scroll events arrive in bursts and the rail ends up chasing the finger.
  assert.match(src, /min-width: 901px\) and \(pointer: fine\)/);
  // Nothing eases toward the scroll position, or the rail is permanently catching up.
  assert.doesNotMatch(read('src/app/globals.css'), /\.inside-rail \{[^}]*transition: transform/);
  // Every page is loaded up front; a lazy one inside a clipped rail arrives blank.
  assert.match(src, /loading="eager"/);
  // It says plainly whose chart these pages are, and shows no written interpretation.
  assert.match(src, /generated by this site for an invented chart/);
});

test('the framework is explained once, not twice', () => {
  assert.equal(existsSync('src/components/home/FrameworkIntro.tsx'), false);
  const story = read('src/components/home/TriadStory.tsx');
  // The definitions the cards used to carry now live in the scenes themselves.
  assert.match(story, /what: 'A map of how your energy is built/);
  assert.match(story, /what: 'The Pythagorean system/);
  assert.match(story, /what: 'Your birth chart, calculated from astronomical data/);
  // And the section carries the anchor the top bar points at.
  assert.match(story, /id="framework" aria-labelledby="framework-heading"/);
  assert.match(story, /They do not predict events and are not medical,\s*legal or financial advice\./);
});

test('lens text clears AAA on the page ground', () => {
  const story = read('src/components/home/TriadStory.tsx');
  // The graphic colours are too dark for small text: #1F8A4D is 4.4:1 and #E0524F is 5.1:1.
  // Text uses the lighter tints, which are 8.4:1, 9.3:1 and 8.2:1.
  for (const tint of ["textColor: '#E5A93C'", "textColor: '#4FBF7F'", "textColor: '#F58A87'"]) {
    assert.ok(story.includes(tint), tint);
  }
  assert.doesNotMatch(story, /color: scene\.color, marginBottom/);
  assert.doesNotMatch(story, /<span style=\{\{ color: s\.color \}\}>/);
});

test('the report section says what the reports cost, and asks for something new', () => {
  const src = read('src/components/home/WhatsInside.tsx');
  // Prices come from the product catalogue, so they cannot drift from the pricing page.
  assert.match(src, /PRODUCT_DISPLAY, PRODUCT_ORDER/);
  assert.match(src, /\{p\.priceLabel\}/);
  assert.match(src, /\{p\.name\}/);
  assert.doesNotMatch(src, /\$\d\d/); // no price typed by hand
  // Three depths, each with one clause of its own.
  for (const slug of ['base-report', 'advanced-sovereign-report', 'sovereign-report']) {
    assert.ok(src.includes(`'${slug}':`), slug);
  }
  // The action here is not a third "calculate": it goes to the reports.
  assert.match(src, /href="\/pricing" className="t3d-cta inside-cta">SEE THE THREE REPORTS/);
  assert.doesNotMatch(src, /CALCULATE MY PROFILE|BEGIN CALCULATION/);
  // And the free calculator is still named as the place to start.
  assert.match(src, /run it first/);
});
